require 'rubygems/package'
require 'fileutils'
require 'json'
require 'digest'

metadata, source, output, proof = ARGV
metadata = JSON.parse(File.read(metadata))
Dir.chdir(source)
spec = Gem::Specification.new do |s|
  s.name = metadata.fetch('name')
  s.version = metadata.fetch('version')
  s.authors = ['Generated schema project']
  s.summary = 'Native Thrift generated Ruby schema'
  s.files = Dir['lib/**/*.rb'].sort
  s.add_runtime_dependency(metadata.fetch('runtime').fetch('name'), '= ' + metadata.fetch('runtime').fetch('version'))
end
Gem::Package.build(spec, false, false, output)
package = Gem::Package.new(output)
package.verify
extracted = File.join(File.dirname(proof), 'gem-files')
package.extract_files(extracted)
hashes = {}
package.contents.each do |name|
  raise 'unexpected native schema gem member' unless name.start_with?('lib/') && name.end_with?('.rb') && !name.split('/').include?('..')
  raise 'native schema gem changed generated bytes' unless File.binread(name) == File.binread(File.join(extracted, name))
  hashes[name.delete_prefix('lib/')] = Digest::SHA256.file(name).hexdigest
end
File.write(proof, JSON.pretty_generate({
  'name' => package.spec.name, 'version' => package.spec.version.to_s,
  'runtimeDependencies' => package.spec.runtime_dependencies.map { |dep| { 'name' => dep.name, 'requirement' => dep.requirement.to_s } },
  'gemSha256' => Digest::SHA256.file(output).hexdigest, 'generatedHashes' => hashes
}) + "\n")
