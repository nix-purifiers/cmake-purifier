"""Install an unchanged native Haxelib ZIP alongside its original SDK graph."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile
import xml.etree.ElementTree as ET


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


spec = json.loads(Path(sys.argv[1]).read_text())
source, out, proof = map(Path, sys.argv[2:5])
record = json.loads((Path(spec['sourceProof']) / 'thrift-haxe.json').read_text())
runtime = json.loads(Path(spec['runtimeProof']).read_text())
out.mkdir(parents=True)
proof.mkdir(parents=True, exist_ok=True)
archive = out / 'library.zip'
payload = {path.relative_to(source).as_posix(): path.read_bytes()
           for path in source.rglob('*') if path.is_file()}
if not payload:
    raise ValueError('empty generated native Haxelib package')
with zipfile.ZipFile(archive, 'w', compression=zipfile.ZIP_STORED) as zipped:
    for name, raw in sorted(payload.items()):
        entry = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
        entry.create_system = 3
        entry.external_attr = 0o100644 << 16
        zipped.writestr(entry, raw)
metadata = json.loads(subprocess.check_output([spec['inspect'], 'zip', str(archive)], text=True))
if metadata != record['package']:
    raise ValueError('native ZIP metadata differs from the original caller manifest')
repository = out / 'repository'
shutil.copytree(spec['repository'], repository, symlinks=True)
for path in [repository, *repository.rglob('*')]:
    if not path.is_symlink():
        path.chmod(path.stat().st_mode | 0o200)
environment = dict(os.environ, HAXELIB_PATH=str(repository) + '/',
                   HAXELIB_PURIFIER_REPOSITORY=str(repository), HAXELIB_PURIFIER_FROZEN='1')
result = subprocess.run([spec['haxelib'], 'install', str(archive), '--always'],
                        env=environment, text=True, capture_output=True)
(proof / 'install.stdout').write_text(result.stdout)
(proof / 'install.stderr').write_text(result.stderr)
if result.returncode:
    raise ValueError('native Haxelib install failed: ' + result.stdout + result.stderr)
folder = repository / metadata['name'].replace('.', ',')
selected = (folder / '.current').read_text().strip()
installed = (folder / selected.replace('.', ',')).resolve(strict=True)
if not installed.is_relative_to(repository):
    raise ValueError('native generated package escaped its own repository')
actual = json.loads(subprocess.check_output([spec['inspect'], 'json', str(installed / 'haxelib.json')], text=True))
if actual != metadata:
    raise ValueError('native installed package metadata changed')
for name, raw in payload.items():
    if (installed / name).read_bytes() != raw:
        raise ValueError('native ZIP install changed generated bytes: ' + name)
with zipfile.ZipFile(archive) as zipped:
    if set(zipped.namelist()) != set(payload):
        raise ValueError('native ZIP payload differs from the generated source tree')
    for name, raw in payload.items():
        if zipped.read(name) != raw:
            raise ValueError('native ZIP changed source bytes: ' + name)
for relative, raw in runtime['markers'].items():
    if (repository / relative).read_text() != raw:
        raise ValueError('native installation changed an original SDK repository selection')
for name, node in runtime['nodes'].items():
    current = repository / node['folder']
    if node['marker'] == '.dev':
        root = Path((current / '.dev').read_text().strip()).resolve(strict=True)
    else:
        root = (current / (current / '.current').read_text().strip().replace('.', ',')).resolve(strict=True)
    for relative, digest in node['files'].items():
        if sha((root / relative).read_bytes()) != digest:
            raise ValueError('native installation changed original SDK dependency bytes: ' + name + '/' + relative)
class_root = (installed / (metadata['classPath'] or '.')).resolve(strict=True)
library_paths = subprocess.check_output([spec['haxelib'], 'path', metadata['name']],
                                       env=environment, text=True)
native_modules = sorted(str(Path(name).with_suffix('')).replace('/', '.')
                        for name in record['generatedHashes'])
command = [spec['haxe'], '-v', '-lib', metadata['name'], *native_modules,
           '--neko', str(proof / 'typed.n'), '--xml', str(proof / 'typed.xml')]
environment['PATH'] = str(Path(spec['haxelib']).parent) + os.pathsep + environment.get('PATH', '')
compiled = subprocess.run(command, env=environment, text=True, capture_output=True)
(proof / 'compiler.stdout').write_text(compiled.stdout)
(proof / 'compiler.stderr').write_text(compiled.stderr)
parsed = {Path(line[len('Parsed '):]).resolve(strict=True)
          for line in compiled.stdout.splitlines() if line.startswith('Parsed ')}
haxe_root = Path(spec['haxeRoot']).resolve(strict=True)
classpath = []
for line in compiled.stdout.splitlines():
    if line.startswith('Classpath: '):
        classpath = [Path(value).resolve() for value in line[len('Classpath: '):].split(';') if value]
sdk_class_roots = [path for path in classpath if path.is_relative_to(haxe_root) and path.is_dir()]
if not sdk_class_roots:
    raise ValueError('native Haxe compiler did not report its original SDK class paths')
for relative in record['generatedHashes']:
    for sdk_root in sdk_class_roots:
        original = sdk_root / relative
        if original.is_file():
            (proof / 'sdk-shadow.json').write_text(json.dumps({
                'module': relative, 'original': str(original), 'originalSha256': sha(original.read_bytes()),
                'actualParsedOrigins': sorted(str(path) for path in parsed if path.name == Path(relative).name),
            }, indent=2) + '\n')
            raise ValueError('generated Haxe module shadows selected compiler SDK: ' + relative)
if compiled.returncode:
    raise ValueError('native Haxe Neko type check failed: ' + compiled.stdout + compiled.stderr)
expected = {str((class_root / relative).resolve(strict=True)) for relative in record['generatedHashes']}
if not expected <= {str(path) for path in parsed}:
    raise ValueError('native Haxe compiler did not parse every original generated module')
for element in ET.parse(proof / 'typed.xml').iter():
    if element.get('file'):
        parsed.add(Path(element.get('file')).resolve(strict=True))
owners = {}
for path in sorted(parsed):
    digest = sha(path.read_bytes())
    if path.is_relative_to(class_root):
        relative = path.relative_to(class_root).as_posix()
        if record['generatedHashes'].get(relative) != digest:
            raise ValueError('native compiler parsed changed generated method bytes')
        owners[str(path)] = {'kind': 'generated', 'sourcePath': relative, 'sha256': digest}
    elif path.is_relative_to(haxe_root):
        owners[str(path)] = {'kind': 'compiler SDK', 'identity': runtime['toolIdentities']['haxe'], 'sha256': digest}
    else:
        matches = []
        for name, node in runtime['nodes'].items():
            folder = repository / node['folder']
            root = (Path((folder / '.dev').read_text().strip()) if node['marker'] == '.dev'
                    else folder / (folder / '.current').read_text().strip().replace('.', ',')).resolve(strict=True)
            if path.is_relative_to(root):
                relative = path.relative_to(root).as_posix()
                if node['files'].get(relative) != digest:
                    raise ValueError('native compiler parsed changed original runtime bytes')
                identities = {json.dumps(item['identity'], sort_keys=True): item['identity']
                              for item in runtime['dependencyOutputs']
                              if Path(node['root']).is_relative_to(Path(item['path']))}
                if len(identities) > 1:
                    raise ValueError('runtime compiler input has ambiguous original Nix owners')
                identity = next(iter(identities.values())) if identities else runtime['producerIdentity']
                matches.append({'kind': 'runtime', 'package': name, 'identity': identity,
                                'sourcePath': relative, 'sha256': digest})
        if len(matches) != 1:
            raise ValueError('native compiler input has no unique original owner: ' + str(path))
        owners[str(path)] = matches[0]
(proof / 'native-typing.json').write_text(json.dumps({
    'target': 'neko', 'command': command, 'nativeLibraryPath': library_paths,
    'compilerClassPaths': [str(path) for path in classpath], 'inputs': owners,
}, indent=2, sort_keys=True) + '\n')
(proof / 'installed-package.json').write_text(json.dumps({
    'metadata': metadata, 'root': str(installed), 'classRoot': str(class_root),
    'archiveSha256': sha(archive.read_bytes()),
    'sourceJoins': {name: sha(raw) for name, raw in payload.items()},
    'runtimeProof': spec['runtimeProof'],
}, indent=2, sort_keys=True) + '\n')
